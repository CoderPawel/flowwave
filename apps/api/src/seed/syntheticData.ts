import { createHash } from 'node:crypto';
import {
  createZonedTimestamp,
  CURRENT_CONSENT_POLICY_VERSIONS,
  ENERGY_ESTIMATE_DISCLAIMER,
  type ZonedTimestamp,
} from '@flowwave/core';
import type { PrismaClient } from '../../generated/prisma/client.js';
import { AuditService } from '../audit/auditService.js';
import { systemClock } from '../common/clock.js';
import { ConsentService } from '../consent/consentService.js';
import { DeviceUsageBucketRepository } from '../importedRecords/deviceUsageBucketRepository.js';
import { HealthSampleRepository } from '../importedRecords/healthSampleRepository.js';
import type { ImportOutcome } from '../importedRecords/idempotentImport.js';
import { SleepSessionRepository } from '../importedRecords/sleepSessionRepository.js';
import type { PrismaService } from '../prisma/prismaService.js';

/**
 * Synthetic demo data. Every record belongs to one user with
 * `is_synthetic = true`; imported records also use the `synthetic` source kind
 * and idempotency keys starting with "synthetic:". Values are generated by
 * fixed formulas, not copied from any real person.
 */
export const SYNTHETIC_USER_ID = syntheticId('user');
export const SYNTHETIC_KEY_PREFIX = 'synthetic:';
const ZONE = 'Europe/Budapest';
const DAYS = ['2026-11-23', '2026-11-24', '2026-11-25'] as const;

/** Deterministic UUID (version 4 layout) so the seed can run repeatedly without duplicates. */
export function syntheticId(name: string): string {
  const hex = createHash('sha256').update(`flowwave-synthetic:${name}`).digest('hex');
  const variant = ((parseInt(hex.charAt(16), 16) & 0x3) | 0x8).toString(16);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

const at = (iso: string): ZonedTimestamp => createZonedTimestamp(iso, ZONE);
type ZonedFields<P extends string> = { [K in `${P}AtUtc`]: Date } & { [K in `${P}TimeZone`]: string } & {
  [K in `${P}UtcOffsetMinutes`]: number;
};
function zoned<P extends string>(prefix: P, iso: string): ZonedFields<P> {
  const t = at(iso);
  return {
    [`${prefix}AtUtc`]: new Date(t.utc),
    [`${prefix}TimeZone`]: t.timeZone,
    [`${prefix}UtcOffsetMinutes`]: t.utcOffsetMinutes,
  } as ZonedFields<P>;
}
const explanation = (factors: readonly { factor: string; detail: string }[], missing: readonly string[] = []) => ({
  factors,
  missing,
  disclaimer: ENERGY_ESTIMATE_DISCLAIMER,
  synthetic: true,
});

export interface SeedSummary {
  readonly importsInserted: number;
  readonly importsUnchanged: number;
  readonly importsUpdated: number;
}

export async function seedSyntheticData(prisma: PrismaService): Promise<SeedSummary> {
  const client: PrismaClient = prisma;
  const userId = SYNTHETIC_USER_ID;
  const deviceId = syntheticId('device');
  const sourceId = syntheticId('source');
  const outcomes: ImportOutcome[] = [];

  await client.user.upsert({
    where: { id: userId },
    create: { id: userId, homeTimeZone: ZONE, sleepGoalMinutes: 450, isSynthetic: true },
    update: {},
  });
  await client.device.upsert({
    where: { id: deviceId },
    create: { id: deviceId, userId, platform: 'android', appVersion: '0.1.0' },
    update: {},
  });
  await client.healthDataSource.upsert({
    where: { id: sourceId },
    create: {
      id: sourceId,
      userId,
      kind: 'synthetic',
      sourceKey: 'synthetic:seed',
      providerName: 'FlowWave synthetic seed data',
    },
    update: {},
  });

  // The synthetic source needs no consent; device usage always does (decision 0014).
  const consents = new ConsentService(prisma, new AuditService(prisma), systemClock);
  await consents.record(userId, {
    id: syntheticId('consent:device_usage'),
    type: 'device_usage',
    state: 'granted',
    scopes: [],
    policyVersion: CURRENT_CONSENT_POLICY_VERSIONS.device_usage,
    decidedAt: at('2026-11-28T00:00:00Z'),
  });

  const samples = new HealthSampleRepository(prisma, consents);
  const sleep = new SleepSessionRepository(prisma, consents);
  const usage = new DeviceUsageBucketRepository(prisma, consents);
  const importedAt = new Date('2026-11-26T00:00:00Z');

  for (const [dayIndex, day] of DAYS.entries()) {
    // Steps per hour, 07:00–20:00 local (UTC+1); 13:00 is deliberately missing.
    for (let hour = 6; hour < 20; hour += 1) {
      const start = `${day}T${String(hour).padStart(2, '0')}:00:00Z`;
      const end = `${day}T${String(hour + 1).padStart(2, '0')}:00:00Z`;
      const value =
        hour === 12
          ? ({ status: 'missing', reason: 'not_recorded' } as const)
          : ({ status: 'present', value: 200 + ((hour * 137 + dayIndex * 61) % 900) } as const);
      outcomes.push(
        (
          await samples.importSample(userId, {
            dataSourceId: sourceId,
            metric: 'steps',
            start: at(start),
            end: at(end),
            value,
            sourceUpdatedAt: importedAt,
            idempotencyKey: `${SYNTHETIC_KEY_PREFIX}steps:${start}`,
          })
        ).outcome,
      );
    }
    // Heart rate per 5 minutes during one morning hour.
    for (let minute = 0; minute < 60; minute += 5) {
      const start = new Date(`${day}T08:00:00Z`).getTime() + minute * 60_000;
      const average = 68 + ((minute + dayIndex * 7) % 15);
      outcomes.push(
        (
          await samples.importSample(userId, {
            dataSourceId: sourceId,
            metric: 'heart_rate',
            start: at(new Date(start).toISOString()),
            end: at(new Date(start + 5 * 60_000).toISOString()),
            value: { status: 'present', value: average, minValue: average - 6, maxValue: average + 9, sampleCount: 5 },
            sourceUpdatedAt: importedAt,
            idempotencyKey: `${SYNTHETIC_KEY_PREFIX}heart_rate:${new Date(start).toISOString()}`,
          })
        ).outcome,
      );
    }
    outcomes.push(
      (
        await samples.importSample(userId, {
          dataSourceId: sourceId,
          metric: 'resting_heart_rate',
          start: at(`${day}T00:00:00Z`),
          end: at(`${day}T23:59:00Z`),
          value: { status: 'present', value: 57 + dayIndex },
          sourceRecordId: `synthetic-rhr-${day}`,
          sourceUpdatedAt: importedAt,
          idempotencyKey: `${SYNTHETIC_KEY_PREFIX}resting_heart_rate:${day}`,
        })
      ).outcome,
    );

    // Sleep: the night before each day. The first night has no stages.
    const bed = new Date(new Date(`${day}T00:00:00Z`).getTime() - (90 - dayIndex * 20) * 60_000).toISOString();
    outcomes.push(
      (
        await sleep.importSession(userId, {
          dataSourceId: sourceId,
          start: at(bed),
          end: at(`${day}T05:45:00Z`),
          stages:
            dayIndex === 0
              ? { status: 'missing', reason: 'source_unavailable' }
              : { status: 'present', deepSleepMinutes: 70 + dayIndex * 5, lightSleepMinutes: 200, remSleepMinutes: 85, awakeMinutes: 20 },
          sourceRecordId: `synthetic-sleep-${day}`,
          sourceUpdatedAt: importedAt,
          idempotencyKey: `${SYNTHETIC_KEY_PREFIX}sleep:${day}`,
        })
      ).outcome,
    );

    // Screen use: four 30-minute buckets in the morning; the last one is missing.
    for (let slot = 0; slot < 4; slot += 1) {
      const start = new Date(new Date(`${day}T08:00:00Z`).getTime() + slot * 30 * 60_000).toISOString();
      const productivity = 600 + slot * 120;
      outcomes.push(
        (
          await usage.importBucket(userId, {
            deviceId,
            bucketStart: at(start),
            metrics:
              slot === 3
                ? { status: 'missing', reason: 'not_yet_synced' }
                : {
                    status: 'present',
                    screenOnSeconds: productivity + 300,
                    unlockCount: 2 + slot,
                    appSwitchCount: 8 + slot * 3,
                    categorySeconds: {
                      productivity,
                      communication: 120,
                      social: 60,
                      entertainment: 0,
                      games: 0,
                      information: 90,
                      other: 30,
                    },
                  },
            sourceUpdatedAt: importedAt,
            idempotencyKey: `${SYNTHETIC_KEY_PREFIX}usage:${start}`,
          })
        ).outcome,
      );
    }

    const id = (name: string) => syntheticId(`${name}:${day}`);
    await client.activitySession.upsert({
      where: { id: id('activity') },
      create: {
        id: id('activity'),
        userId,
        dataSourceId: sourceId,
        activityType: 'walking',
        ...zoned('start', `${day}T16:00:00Z`),
        ...zoned('end', `${day}T16:40:00Z`),
        ...(dayIndex === 1 ? { intensityMissingReason: 'user_skipped' as const } : { intensity: 'moderate' as const }),
        sourceUpdatedAtUtc: importedAt,
        idempotencyKey: `${SYNTHETIC_KEY_PREFIX}activity:${day}`,
      },
      update: {},
    });
    await client.selfCheckIn.upsert({
      where: { id: id('check_in') },
      create: {
        id: id('check_in'),
        userId,
        ...zoned('recorded', `${day}T08:30:00Z`),
        selfReportedEnergy: 2 + dayIndex,
        sleepDurationMinutes: 400 + dayIndex * 25,
        sleepDurationSource: 'manual_check_in',
      },
      update: {},
    });
    await client.mealEvent.upsert({
      where: { id: id('meal') },
      create: { id: id('meal'), userId, ...zoned('eaten', `${day}T11:30:00Z`), mealType: 'lunch', size: 'medium' },
      update: {},
    });
    await client.caffeineEvent.upsert({
      where: { id: id('caffeine') },
      create: {
        id: id('caffeine'),
        userId,
        ...zoned('consumed', `${day}T07:15:00Z`),
        ...(dayIndex === 2 ? { amountMissingReason: 'user_skipped' as const } : { amount: 'small' as const }),
      },
      update: {},
    });
    await client.restEvent.upsert({
      where: { id: id('rest') },
      create: {
        id: id('rest'),
        userId,
        restType: 'short_break',
        ...zoned('start', `${day}T10:00:00Z`),
        ...zoned('end', `${day}T10:15:00Z`),
      },
      update: {},
    });
    await client.focusSession.upsert({
      where: { id: id('focus') },
      create: {
        id: id('focus'),
        userId,
        ...zoned('start', `${day}T08:15:00Z`),
        ...zoned('end', `${day}T09:05:00Z`),
        plannedDurationMinutes: 45,
        outcome: 'completed',
        selfRatedFocus: 6 + dayIndex,
      },
      update: {},
    });
    await client.dailyScore.upsert({
      where: { id: id('daily_score') },
      create: {
        id: id('daily_score'),
        userId,
        localDate: new Date(`${day}T00:00:00Z`),
        timeZone: ZONE,
        scoreType: 'energy',
        ...(dayIndex === 0
          ? { status: 'insufficient_data' as const, inputCoverageRatio: 0.4 }
          : { status: 'computed' as const, scoreValue: 55 + dayIndex * 10, inputCoverageRatio: 1 }),
        calculationVersion: '1.0.0',
        explanation:
          dayIndex === 0
            ? explanation([], ['sleep_stages'])
            : explanation([
                { factor: 'self_reported_energy', detail: 'Synthetic check-in value.' },
                { factor: 'sleep_duration', detail: 'Synthetic sleep compared with the synthetic goal.' },
              ]),
        computedAtUtc: importedAt,
      },
      update: {},
    });
    await client.rhythmBucket.upsert({
      where: { id: id('rhythm') },
      create: {
        id: id('rhythm'),
        userId,
        ...zoned('bucketStart', `${day}T08:00:00Z`),
        status: 'computed',
        state: dayIndex === 2 ? 'flow' : 'ready',
        energyLevel: 60 + dayIndex * 5,
        confidenceRatio: 0.5,
        calculationVersion: '1.0.0',
        explanation: explanation([{ factor: 'morning_check_ins', detail: 'Synthetic history of morning check-ins.' }]),
        computedAtUtc: importedAt,
      },
      update: {},
    });
  }

  await client.recommendation.upsert({
    where: { id: syntheticId('recommendation') },
    create: {
      id: syntheticId('recommendation'),
      userId,
      kind: 'focus_block',
      templateKey: 'focus_block.morning_window',
      parameters: { startLocal: '09:00', durationMinutes: 45 },
      explanation: explanation([{ factor: 'rhythm_state', detail: 'Synthetic ready state at 09:00 on recent days.' }]),
      ...zoned('validFrom', '2026-11-26T07:00:00Z'),
      validUntilAtUtc: new Date('2026-11-26T11:00:00Z'),
      calculationVersion: '1.0.0',
    },
    update: {},
  });
  await client.syncCheckpoint.upsert({
    where: { userId_deviceId_stream: { userId, deviceId, stream: 'check_in' } },
    create: { userId, deviceId, stream: 'check_in', cursor: 'synthetic-0', lastSyncedAtUtc: importedAt },
    update: {},
  });
  await client.auditEvent.upsert({
    where: { id: syntheticId('audit:account_created') },
    create: {
      id: syntheticId('audit:account_created'),
      userId,
      action: 'account_created',
      metadata: { synthetic: true },
      occurredAtUtc: importedAt,
    },
    update: {},
  });

  const count = (outcome: ImportOutcome) => outcomes.filter((o) => o === outcome).length;
  return {
    importsInserted: count('inserted'),
    importsUnchanged: count('unchanged'),
    importsUpdated: count('updated') + count('stale'),
  };
}
